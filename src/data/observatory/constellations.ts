/** 星座恒星的天空平面绝对坐标 */
export function starWorldPosition(
  constellation: Constellation,
  starIndex: number
) {
  const star = constellation.stars[starIndex];
  return {
    x: constellation.position.x + star.x,
    y: constellation.position.y + star.y,
  };
}
